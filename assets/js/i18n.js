/* ── language engine ── */
let LANG = 'en';
const t = (k, vars) => {
  let s = (I18N[LANG] && I18N[LANG][k]) ?? I18N.en[k] ?? k;
  if (vars) for (const [k2, v] of Object.entries(vars)) s = s.replaceAll('{' + k2 + '}', v);
  return s;
};

function applyI18n() {
  const dict = I18N[LANG];
  document.documentElement.lang = LANG;
  document.documentElement.dir = dict.dir;
  document.title = dict.title;
  const md = document.querySelector('meta[name="description"]');
  if (md) md.setAttribute('content', dict.desc);
  document.querySelectorAll('[data-i18n]').forEach(el => { el.innerHTML = dict[el.dataset.i18n] ?? el.innerHTML; });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = dict[el.dataset.i18nPh] ?? el.placeholder; });
  document.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = dict[el.dataset.i18nTitle] ?? el.title; });
  // re-render dynamic areas that hold translated strings
  if (typeof renderList === 'function' && typeof window.CACHE_OBJ !== 'undefined' && window.CACHE_OBJ && window.MAIL_TAB_NOW !== 'sched') renderList(window.CACHE_OBJ.list || []);
  if (typeof updateLangButtons === 'function') updateLangButtons();
}

function setLang(l, save) {
  if (!I18N[l]) l = 'en';
  LANG = l;
  try { localStorage.setItem('tm_lang', l); } catch(e) {}
  if (save !== false) {
    // persist on the server session (and account when logged in)
    fetch('/api/lang.php', {method:'POST', credentials:'same-origin',
      headers:{'Content-Type':'application/json'}, body: JSON.stringify({lang: l})}).catch(()=>{});
  }
  applyI18n();
}

function initLang() {
  let l = null;
  try { l = localStorage.getItem('tm_lang'); } catch(e) {}
  // QR login token in URL? handled in boot — language comes after login
  setLang(I18N[l] ? l : 'en', false);
}
